// beforeRes: candidate insertion points, first match wins. Some pages omit
// </head> entirely (valid HTML - about.html does), so the head insert falls
// back to "just before <body>", which is still inside the implied head.
function swapOrInsert(html, [a, b], block, beforeRes, label) {
  const re = new RegExp(esc(a) + '[\\s\\S]*?' + esc(b));
  if (re.test(html)) return html.replace(re, a + '\n' + block + '\n' + b);
  for (const beforeRe of [].concat(beforeRes)) {
    const m = html.match(beforeRe);
    if (m) return html.slice(0, m.index) + a + '\n' + block + '\n' + b + '\n' + html.slice(m.index);
  }
  throw new Error(`${label}: nowhere to insert`);
}

function processPage(file) {
  const full = path.join(ROOT, file);
  const raw = fs.readFileSync(full, 'utf8');
  const eol = detectEOL(raw);
  let html = toEOL(raw, '\n');
  const isPortal = isPortalPage(file);
  const prefix = prefixFor(file);

  html = stampHtmlTag(html, file);
  html = stampNoindex(html, file);
  html = stampMeta(html, file);
  html = stampSkipLink(html);
  html = swapOrInsert(html, S.css, `<link rel="stylesheet" href="${prefix}${CSS_HREF}">`, [/<\/head>/, /<body[^>]*>/], `${file} chrome css`);
  html = swapOrInsert(html, S.js, `<script src="${prefix}${JS_SRC}" defer></script>`, /<\/body>/, `${file} chrome js`);

  const footer = relativize(FOOTER_HTML, prefix);
  const footRe = new RegExp(esc(S.footer[0]) + '[\\s\\S]*?' + esc(S.footer[1]));
  if (footRe.test(html)) {
    html = html.replace(footRe, S.footer[0] + '\n' + footer + '\n' + S.footer[1]);
  } else {
    const old = html.match(/<footer[\s\S]*?<\/footer>/);
    if (!old) throw new Error(`${file}: no <footer> to replace`);
    html = html.replace(old[0], S.footer[0] + '\n' + footer + '\n' + S.footer[1]);
  }
  if (!isPortal) {
    // the connect block sits just before the chrome script
    const conRe = new RegExp(esc(S.connect[0]) + '[\\s\\S]*?' + esc(S.connect[1]));
    if (conRe.test(html)) html = html.replace(conRe, S.connect[0] + '\n' + CONNECT_HTML + '\n' + S.connect[1]);
    else html = html.replace(S.js[0], S.connect[0] + '\n' + CONNECT_HTML + '\n' + S.connect[1] + '\n' + S.js[0]);
  }

  // Run last so the noscript block stays immediately after <body>, before
  // the skip link, and generated portal pages never inherit marketing tags.
  html = stampGtm(html, file);
  fs.writeFileSync(full, toEOL(html, eol));
  return isPortal ? 'portal' : 'page';
}

