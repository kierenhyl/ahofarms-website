// Generates the portal pages from the registry in lib/portals.js:
//   portal/index.html                       the public hub
//   portal/<id>/login.html                  sign in            (public)
//   portal/<id>/request-access.html         request access     (public)
//   portal/<id>/forgot.html                 forgot password    (public)
//   portal/<id>/reset.html                  set / reset password (public, token in link)
//   portal/<id>/home.html                   dashboard          (protected by middleware.js)
//   portal/<id>/account.html                account            (protected by middleware.js)
//
// Each page carries empty AHO sentinel blocks; the shared header, footer
// and chrome are stamped by the usual run afterwards:
//   node scripts/build-portals.js && node scripts/propagate-nav.js && node scripts/propagate-chrome.js && node scripts/check-nav.js
// Links inside the pages use Vercel's clean, extensionless public routes.
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { stampTemporaryNoindex } = require('./indexing');

const ROOT = path.join(__dirname, '..');
const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const FONTS_HREF = 'https://fonts.googleapis.com/css2?family=Cormorant+Garamond:ital,wght@0,400;0,500;1,400;1,500&family=Inter:wght@400;500;600&display=swap';
const ver = rel => crypto.createHash('sha1').update(fs.readFileSync(path.join(ROOT, rel))).digest('hex').slice(0, 8);
const LEGAL = 'Aho Farms products are prescription medicines and are not for general sale. Portal access is restricted to verified professionals and partners; every request is reviewed by Aho Farms before an account is approved.';

const S = {
  nav: ['<!-- AHO:NAV:START - generated by scripts/propagate-nav.js, do not edit by hand -->', '<!-- AHO:NAV:END -->'],
  css: ['<!-- AHO:CHROME:CSS:START - generated by scripts/propagate-chrome.js, do not edit by hand -->', '<!-- AHO:CHROME:CSS:END -->'],
  js: ['<!-- AHO:CHROME:JS:START - generated by scripts/propagate-chrome.js, do not edit by hand -->', '<!-- AHO:CHROME:JS:END -->'],
  footer: ['<!-- AHO:FOOTER:START - generated by scripts/propagate-nav.js, do not edit by hand -->', '<!-- AHO:FOOTER:END -->'],
};

function shell({ depth, title, description, portalId, page, main, noindex, scripts = [] }) {
  const rel = '../'.repeat(depth);
  const fav = (fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8').match(/<link rel="icon"[^>]*>/) || [''])[0]
    .replace(/href="(?!https?:|\/|data:)/, `href="${rel}`);
  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${esc(title)}</title>
  <meta name="description" content="${esc(description)}">${noindex ? '\n  <meta name="robots" content="noindex, nofollow">' : ''}${fav ? '\n  ' + fav : ''}
  <link rel="preconnect" href="https://fonts.googleapis.com">
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
  <link href="${FONTS_HREF}" rel="stylesheet">
  ${S.css[0]}
  ${S.css[1]}
  <link rel="stylesheet" href="${rel}assets/aho-portal.css?v=${ver('assets/aho-portal.css')}">
</head>
<body data-portal="${esc(portalId)}" data-page="${esc(page)}">
${S.nav[0]}
${S.nav[1]}
<main id="main" class="pt-main">
${main}
</main>
${S.footer[0]}
${S.footer[1]}
${S.js[0]}
${S.js[1]}
${scripts.map(x => `<script src="${rel}${x}?v=${ver(x)}" defer></script>\n`).join('')}<script src="${rel}assets/aho-portal.js?v=${ver('assets/aho-portal.js')}" defer></script>
</body>
</html>
`;
}

const msg = (role = 'alert', live = 'assertive') => `<p class="pt-msg" role="${role}" aria-live="${live}" tabindex="-1" hidden></p>`;
const fieldError = '<span class="pt-field-error" aria-live="polite"></span>';

function field(f, { full = false, id } = {}) {
  const fid = id || `f-${f.name}`;
  const req = f.required ? ' data-required required aria-required="true"' : '';
  const ac = f.autocomplete ? ` autocomplete="${f.autocomplete}"` : '';
  const star = f.required ? ' <span aria-hidden="true">*</span>' : '';
  let control;
  if (f.type === 'select') {
    control = `<select id="${fid}" name="${f.name}"${req}>\n        <option value="">Select…</option>\n${f.options.map(o => `        <option value="${esc(o)}">${esc(o)}</option>`).join('\n')}\n      </select>`;
  } else if (f.type === 'textarea') {
    control = `<textarea id="${fid}" name="${f.name}" rows="${f.rows || 4}"${req}${ac}></textarea>`;
  } else {
    const im = f.type === 'tel' ? ' inputmode="tel"' : f.type === 'email' ? ' inputmode="email"' : '';
    control = `<input id="${fid}" name="${f.name}" type="${f.type}"${im}${ac}${req}>`;
  }
  return `      <div class="field${full || f.type === 'textarea' ? ' field--full' : ''}">
        <label for="${fid}">${esc(f.label)}${star}</label>
        ${control}${f.hint ? `\n        <small>${esc(f.hint)}</small>` : ''}
        ${fieldError}
      </div>`;
}

const pwField = (name, label, ac, hint) => `      <div class="field">
        <label for="f-${name}">${label}</label>
        <div class="pt-pw"><input id="f-${name}" name="${name}" type="password" autocomplete="${ac}" data-required required aria-required="true"${name !== 'current' ? ' minlength="10"' : ''}><button type="button" class="pt-pw-toggle" aria-pressed="false">Show</button></div>${hint ? `\n        <small>${hint}</small>` : ''}
        ${fieldError}
      </div>`;

function switchLine(p, all, text) {
  const others = all.filter(o => o.id !== p.id).map(o => `<a href="/portal/${o.id}/login">${esc(o.name)}</a>`).join('<span>·</span>');
  return `<p class="pt-switch">${text} ${others}</p>`;
}

